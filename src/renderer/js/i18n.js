  const DICTS = { spanish: ES, english: EN };
  let lang = 'spanish';

  function setLang(l) { lang = DICTS[l] ? l : 'english'; document.documentElement.lang = lang === 'spanish' ? 'es' : 'en'; }
  function getLang() { return lang; }
  function locale() { return lang === 'spanish' ? 'es-ES' : 'en-GB'; }

  function t(key, vars) {
    let s = (DICTS[lang] && DICTS[lang][key]) ?? EN[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  }

  function apply(rootEl) {
    const scope = rootEl || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
  }

  root.PP = root.PP || {};
  Object.assign(root.PP, { t, setLang, getLang, locale, applyI18n: apply, _dicts: DICTS });
